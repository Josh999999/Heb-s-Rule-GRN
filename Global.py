# --- Normalise the two images to a common square size so they are valid, equal-length targets ---
def _square_pad(img, S, fill=1):
    out = np.full((S, S), fill, dtype=int)
    h, w = img.shape
    out[:min(h, S), :min(w, S)] = img[:min(h, S), :min(w, S)]
    return out

